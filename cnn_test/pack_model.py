"""Pack acc_demo's exported model into the existing UART loader format.

Run from the repository root:
    python pack_model.py
    python pack_model.py --program-dmem build/cnn_dmem.bin

Only Python's standard library is needed. Model parameters keep their original
INT8/INT32 byte layout. The loader packet reverses each four-byte word because
the UART loader assembles incoming bytes most-significant byte first.
"""

import argparse
import hashlib
import json
from pathlib import Path
import struct


ROOT = Path(__file__).resolve().parent
CPU_DATA_BASE = 0x80000000
DDR_DATA_BASE = 0x10000000
DATA_REGION_BYTES = 128 * 1024
MODEL_BASE_OFFSET = 64 * 1024
DMEM_PREAMBLE = b"\xd0" * 4
POSTAMBLE = b"\xe0" * 4
LAYERS = ("conv1", "conv2", "fc1", "fc2", "fc3")

# These are the padded PE layouts exported by the current acc_demo.py model.
# A label is one byte; packing aligns the NEXT entry to a four-byte boundary.
MODEL_FILES = (
    ("test_images", 1024),
    ("conv1_weight", 400),
    ("conv1_bias", 24),
    ("conv2_weight", 2400),
    ("conv2_bias", 64),
    ("fc1_weight", 38400),
    ("fc1_bias", 384),
    ("fc2_weight", 6144),
    ("fc2_bias", 256),
    ("fc3_weight", 1024),
    ("fc3_bias", 40),
    ("test_labels", 1),
)


def align4(value):
    return (value + 3) & ~3


def reverse_words(data):
    """Convert between little-endian memory bytes and loader wire bytes."""
    if len(data) % 4:
        raise ValueError("Loader payload length must be a multiple of four")
    result = bytearray(len(data))
    for lane in range(4):
        result[lane::4] = data[3 - lane::4]
    return bytes(result)


def loader_packet(data, base_offset):
    if not data or base_offset < 0 or base_offset % 4:
        raise ValueError("Loader payload must be nonempty; base must be aligned")
    data = data.ljust(align4(len(data)), b"\0")
    if base_offset + len(data) > DATA_REGION_BYTES:
        raise ValueError("Packet exceeds the loader's 128 KiB data region")
    return (DMEM_PREAMBLE + struct.pack(">II", len(data), base_offset)
            + reverse_words(data) + POSTAMBLE)


def read_program_dmem(path):
    """Decode an already wrapped D0 file, not objcopy's raw .data binary."""
    packet = path.read_bytes()
    if len(packet) < 20 or packet[:4] != DMEM_PREAMBLE:
        raise ValueError(f"{path}: expected a wrapped D0 loader file")
    size, base = struct.unpack(">II", packet[4:12])
    if (not size or size % 4 or base % 4 or len(packet) != size + 16
            or packet[-4:] != POSTAMBLE):
        raise ValueError(f"{path}: invalid loader length, alignment or trailer")
    if base + size > MODEL_BASE_OFFSET:
        raise ValueError("Program data overlaps the model region at offset 0x10000")
    return base, reverse_words(packet[12:-4])


def build_model(model_dir):
    scales = json.loads((model_dir / "scales.json").read_text(encoding="utf-8-sig"))
    image = bytearray()
    entries = []

    def append_entry(name, data):
        offset = align4(len(image))
        image.extend(b"\0" * (offset - len(image)))
        image.extend(data)
        data_offset = MODEL_BASE_OFFSET + offset
        entries.append({
            "name": name,
            "offset_in_model": offset,
            "loader_offset": data_offset,
            "cpu_address": CPU_DATA_BASE + data_offset,
            "ddr_address": DDR_DATA_BASE + data_offset,
            "size_bytes": len(data),
            "sha256": hashlib.sha256(data).hexdigest(),
        })

    for name, expected_size in MODEL_FILES:
        path = model_dir / (name + ".bin")
        data = path.read_bytes()
        if len(data) != expected_size:
            raise ValueError(f"{path}: expected {expected_size} bytes, got {len(data)}")
        append_entry(name, data)

    quantization = {}
    quant_data = bytearray()
    for name in LAYERS:
        mult = scales[name + "_quant_mult"]
        shift = scales[name + "_quant_shift"]
        if (type(mult) is not int or not 0 <= mult <= 0xFFFFFFFF
                or type(shift) is not int or not 0 <= shift <= 63):
            raise ValueError(f"{name}: invalid MULT or SHIFT")
        quantization[name] = {"mult": mult, "shift": shift}
        quant_data.extend(struct.pack("<II", mult, shift))
    append_entry("quant_params", quant_data)
    image.extend(b"\0" * (align4(len(image)) - len(image)))
    if len(image) > DATA_REGION_BYTES - MODEL_BASE_OFFSET:
        raise ValueError("Model exceeds the reserved upper 64 KiB region")
    return bytes(image), entries, quantization


def make_header(entries, quantization, model_size):
    lines = [
        "/* Generated by pack_model.py. All addresses and lengths are bytes. */",
        "/* Compile firmware with linker_cnn.ld to reserve the model region. */",
        "#ifndef MODEL_LAYOUT_H", "#define MODEL_LAYOUT_H", "",
        "#define MODEL_BASE_OFFSET 0x00010000u",
        "#define MODEL_CPU_BASE    0x80010000u",
        "#define MODEL_DDR_BASE    0x10010000u",
        f"#define MODEL_SIZE_BYTES  {model_size}u", "",
    ]
    for entry in entries:
        prefix = "MODEL_" + entry["name"].upper()
        lines.extend([
            f"#define {prefix}_OFFSET   0x{entry['loader_offset']:08X}u",
            f"#define {prefix}_CPU_ADDR 0x{entry['cpu_address']:08X}u",
            f"#define {prefix}_DDR_ADDR 0x{entry['ddr_address']:08X}u",
            f"#define {prefix}_BYTES    {entry['size_bytes']}u", "",
        ])
    for name, values in quantization.items():
        prefix = "MODEL_" + name.upper()
        lines.extend([
            f"#define {prefix}_QUANT_MULT  {values['mult']}u",
            f"#define {prefix}_QUANT_SHIFT {values['shift']}u", "",
        ])
    lines.extend(["#endif", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-dir", type=Path, default=ROOT / "soc_export_int8")
    parser.add_argument("--out-dir", type=Path, default=ROOT / "ddr_model")
    parser.add_argument("--program-dmem", type=Path,
                        help="Optional existing D0 firmware .data package; merge into cnn_dmem.bin")
    args = parser.parse_args()
    try:
        image, entries, quantization = build_model(args.model_dir)
        model_packet = loader_packet(image, MODEL_BASE_OFFSET)
        combined = None
        if args.program_dmem:
            base, program = read_program_dmem(args.program_dmem)
            memory = bytearray(MODEL_BASE_OFFSET + len(image))
            memory[base:base + len(program)] = program
            memory[MODEL_BASE_OFFSET:] = image
            combined = loader_packet(bytes(memory), 0)
        manifest = {
            "network": "1x32x32 -> 6x28x28 -> 6x14x14 -> 16x10x10 -> 16x5x5 -> 400 -> 96 -> 64 -> 10",
            "model_size_bytes": len(image),
            "loader_base_offset": MODEL_BASE_OFFSET,
            "cpu_base_address": CPU_DATA_BASE + MODEL_BASE_OFFSET,
            "ddr_base_address": DDR_DATA_BASE + MODEL_BASE_OFFSET,
            "loader_packet": "D0*4 + big-endian length + big-endian offset + reversed 4-byte words + E0*4",
            "memory_payload_byte_order": "Original INT8 bytes; little-endian INT32 bias and quantization table",
            "quantization_order": list(LAYERS),
            "quantization": quantization,
            "entries": entries,
            "program_dmem_source": str(args.program_dmem) if args.program_dmem else None,
        }
        args.out_dir.mkdir(parents=True, exist_ok=True)
        (args.out_dir / "model_data.raw").write_bytes(image)
        (args.out_dir / "model_data.bin").write_bytes(model_packet)
        (args.out_dir / "model_layout.json").write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        (args.out_dir / "model_layout.h").write_text(
            make_header(entries, quantization, len(image)), encoding="utf-8")
        if combined is not None:
            (args.out_dir / "cnn_dmem.bin").write_bytes(combined)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        parser.exit(2, f"pack_model: {exc}\n")
    print(f"Model: {len(image)} bytes at DDR 0x{DDR_DATA_BASE + MODEL_BASE_OFFSET:08X}")
    for entry in entries:
        print(f"  {entry['name']:16s} DDR=0x{entry['ddr_address']:08X} bytes={entry['size_bytes']}")
    print(f"Output: {args.out_dir.resolve()}")
    if combined is not None:
        print("Use cnn_dmem.bin as peqflash.py -dmembin; IMEM remains a separate C0 file.")
    else:
        print("model_data.bin contains only the model, not firmware .data.")
        print("Use --program-dmem with the firmware D0 file to create cnn_dmem.bin.")


if __name__ == "__main__":
    main()
